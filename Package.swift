// swift-tools-version: 6.0
// The swift-tools-version declares the minimum version of Swift required to build this package.

import PackageDescription

// potion-code-16M-v2 ships inside the binary: the linker copies each file into a section of a read-only
// __POTION segment, which PotionModel.bundled() reads in place. One self-contained executable, no download.
let potion = Context.packageDirectory + "/Models/potion-code-16M-v2/"
let potionSections = [("__model", "model.safetensors"), ("__tokenizer", "tokenizer.json"), ("__config", "config.json")]
    .flatMap { section, file in ["-Xlinker", "-sectcreate", "-Xlinker", "__POTION", "-Xlinker", section, "-Xlinker", potion + file] }

// fff is built by `make fff` (scripts/build-fff.sh) and linked statically, so smcli-service stays one file.
// Only SmcliFFF (and so only smcli-service) links it. libgit2 inside fff needs these system libraries.
// `.build/fff/lib/libfff_c.a` holds the architecture(s) that script built: thin by default, universal for FFF_ARCHS.
let fff = Context.packageDirectory + "/.build/fff/lib/libfff_c.a"
let fffLink = [fff, "-lz", "-liconv", "-framework", "CoreFoundation", "-framework", "Security"]

let package = Package(
    name: "smcli",
    // ProximaKit's hybrid search requires macOS 14 (Accelerate/NaturalLanguage).
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "smcli", targets: ["smcli"]),
        .executable(name: "smcli-service", targets: ["smcli-service"]),
    ],
    dependencies: [
        .package(url: "https://github.com/vivekptnk/ProximaKit", from: "1.8.0"),
    ],
    targets: [
        // Apple platforms ship an SQLite3 module; Linux links the system library instead.
        .systemLibrary(name: "CSQLite", pkgConfig: "sqlite3", providers: [.apt(["libsqlite3-dev"])]),
        // History storage, capture filters and the service protocol, shared by the CLI and the service.
        // Neither the CLI nor this library may link fff; only smcli-service will.
        .target(name: "SmcliCore", dependencies: [
            .target(name: "CSQLite", condition: .when(platforms: [.linux])),
        ]),
        // Command search: the hybrid index, embedding models and native history files. Used by the service,
        // which keeps the index open, and by the CLI when no service is running.
        .target(name: "SmcliSearch", dependencies: [
            "SmcliCore",
            // Apple-only; on Linux `smcli search` reports that it is unavailable.
            .product(name: "ProximaKit", package: "ProximaKit", condition: .when(platforms: [.macOS])),
            .product(name: "ProximaEmbeddings", package: "ProximaKit", condition: .when(platforms: [.macOS])),
        ]),
        // The pinned fff C API (header generated by scripts/build-fff.sh) and the Swift ownership wrapper over it.
        .systemLibrary(name: "CFFF"),
        .target(name: "SmcliFFF", dependencies: ["CFFF"],
                linkerSettings: [.unsafeFlags(fffLink, .when(platforms: [.macOS]))]),
        // Both executables embed the model: each must be able to search on its own.
        .executableTarget(name: "smcli", dependencies: ["SmcliCore", "SmcliSearch"],
                          linkerSettings: [.unsafeFlags(potionSections, .when(platforms: [.macOS]))]),
        // The long-lived owner of history state; clients reach it over a Unix-domain socket.
        .executableTarget(name: "smcli-service", dependencies: ["SmcliCore", "SmcliSearch", "SmcliFFF"],
                          linkerSettings: [.unsafeFlags(potionSections, .when(platforms: [.macOS]))]),
        .testTarget(name: "smcliTests", dependencies: ["smcli", "SmcliCore", "SmcliSearch", "SmcliFFF"]),
    ]
)
