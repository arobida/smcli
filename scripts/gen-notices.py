#!/usr/bin/env python3
"""Generates THIRD_PARTY_NOTICES.md from what the build actually pulls in.

Usage: python3 scripts/gen-notices.py   (run `make fff` first: it needs the pinned fff source in .build/fff/source and
a resolved SwiftPM checkout of taladb-swift in .build/checkouts). Rerun whenever the fff pin, its features or the
Swift dependencies change. It reads each Rust crate's own license files; it does not interpret them, so the license
expressions are what the crates declare. This is not legal advice.
"""
import glob
import hashlib
import json
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest = f"{root}/.build/fff/source/Cargo.toml"
targets = ["aarch64-apple-darwin", "x86_64-apple-darwin"]
if not os.path.exists(manifest):
    sys.exit("Run `make fff` first: the pinned fff source is missing.")


def crates_for(triple):
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--manifest-path", manifest, "--locked", "--filter-platform", triple, "--format-version", "1"],
        stderr=subprocess.DEVNULL))
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = next(p["id"] for p in meta["packages"] if p["name"] == "fff-c")
    seen, stack = set(), [start]
    while stack:  # linked (normal) dependencies only: no build or dev dependencies
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return {packages[i]["id"]: packages[i] for i in seen}


crates = {}
for triple in targets:
    crates.update(crates_for(triple))
crates = sorted(crates.values(), key=lambda p: (p["name"], p["version"]))
third_party = [c for c in crates if c["source"]]  # fff's own crates are covered by fff's LICENSE


def read(path):
    with open(path, errors="replace") as handle:
        return handle.read().strip()


def license_files(directory):
    names = sorted(n for n in os.listdir(directory) if n.split(".")[0].upper() in ("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")
                   or n.upper().startswith(("LICENSE-", "LICENCE-", "COPYING-")))
    return [os.path.join(directory, n) for n in names if os.path.isfile(os.path.join(directory, n))]


texts = {}  # sha256 -> (text, [crate labels])
missing = []
for crate in third_party:
    files = license_files(os.path.dirname(crate["manifest_path"]))
    if not files:
        missing.append(f"{crate['name']} {crate['version']}")
    for path in files:
        text = read(path)
        entry = texts.setdefault(hashlib.sha256(text.encode()).hexdigest(), (text, []))
        entry[1].append(f"{crate['name']} {crate['version']}")

out = []
w = out.append
w("# Third-party notices\n")
w("Generated by `scripts/gen-notices.py`; do not edit by hand. It covers what `smcli` and `smcli-service` link or embed: ")
w("the Swift dependency taladb-swift with its prebuilt TalaDBFFI engine, the bundled search model, the pinned fff library with the Rust crates and C code it ")
w("brings, and the notices those licenses require. See `docs/fff-licenses.md` for the audit and the open xdiff (LGPL) question.\n")
w("**smcli's own license is not decided yet.** The repository has no `LICENSE` file; that is an open decision for the owner.\n")

w("## Swift dependencies\n")
tala = f"{root}/.build/checkouts/taladb-swift"
tala_version = next(p["state"]["version"] for p in json.load(open(f"{root}/Package.resolved"))["pins"] if p["identity"] == "taladb-swift")
engine_ref = next(l.split("=", 1)[1].strip() for l in open(f"{tala}/engine.properties") if l.startswith("ref="))
w(f"### taladb-swift {tala_version} (MIT OR Apache-2.0)\n\nhttps://github.com/taladb/taladb-swift (`TalaDB`), used under the MIT option.\n")
w("```text\n" + read(f"{tala}/LICENSE-MIT") + "\n```\n")
w(f"### TalaDBFFI.xcframework (taladb engine {engine_ref}, prebuilt binary)\n\n")
w(f"https://github.com/taladb/taladb, release {engine_ref}, downloaded by SwiftPM as a binary target and statically linked. ")
w("The xcframework ships no license file of its own; taladb-swift declares MIT OR Apache-2.0 for the package, and the text above ")
w("is taken to cover the engine. The Rust crates compiled into the engine (redb and others) are not enumerated here: ")
w("that needs the engine's Cargo.lock at this tag and is an open item.\n")

w("## Bundled model\n")
w("### potion-code-16M-v2 (MIT)\n")
w("https://huggingface.co/minishlab/potion-code-16M-v2, revision `e9d2a44ca6a05ac6685f3b23709ea57eb7352d5b`, by Minish Lab, ")
w("embedded in both executables (`Models/potion-code-16M-v2`). The model card declares the MIT license; the repository ")
w("ships no separate license file for it, so the copyright line is the publisher's and the text below is the standard MIT license.\n")
w("```text\nMIT License\n\nCopyright (c) Minish Lab\n\n" + read(f"{root}/tools/fff/LICENSE").split("\n\n", 2)[2] + "\n```\n")

w("## fff (MIT)\n")
w("https://github.com/dmtrKovalenko/fff v0.11.0 (`95fd777c2529fc7b4d7572dabff64cc07268f2c5`), statically linked into `smcli-service` only.\n")
w("```text\n" + read(f"{root}/tools/fff/LICENSE") + "\n```\n")

w("## Bundled C code inside fff's dependencies\n")
w("Authoritative texts, copied from the crates that carry them.\n")
git2 = next(c for c in third_party if c["name"] == "libgit2-sys")
w("### libgit2 (GPL-2.0 with linking exception; bundles xdiff LGPL-2.1+, PCRE BSD, llhttp/SHA1DC MIT)\n")
w(f"From `libgit2-sys {git2['version']}`, `libgit2/COPYING`. **xdiff is LGPL: see the open decision in `docs/fff-licenses.md`.**\n")
w("```text\n" + read(f"{os.path.dirname(git2['manifest_path'])}/libgit2/COPYING") + "\n```\n")
lmdb = next(c for c in third_party if c["name"] == "lmdb-master-sys")
lmdb_license = glob.glob(f"{os.path.dirname(lmdb['manifest_path'])}/lmdb/libraries/liblmdb/LICENSE")
w("### LMDB (OpenLDAP Public License)\n")
w(f"From `lmdb-master-sys {lmdb['version']}`.\n")
w("```text\n" + (read(lmdb_license[0]) if lmdb_license else "LICENSE file not found in the crate; see lmdb-master-sys.") + "\n```\n")

w("## Rust crates linked by fff\n")
w(f"{len(third_party)} third-party crates for macOS arm64 and x86_64 (linked dependencies only), with the license expression each declares.\n")
w("| Crate | Version | License |\n|---|---|---|")
for crate in third_party:
    w(f"| {crate['name']} | {crate['version']} | {crate['license'] or 'see license file'} |")
w("")
if missing:
    w("No license file shipped in the crate source (license taken from `Cargo.toml` only): " + ", ".join(missing) + ".\n")
w("### License texts\n")
w("Each distinct text found in the crates' sources, with the crates that ship it.\n")
for text, owners in sorted(texts.values(), key=lambda entry: entry[1][0]):
    w("#### " + ", ".join(sorted(set(owners))) + "\n")
    w("```text\n" + text + "\n```\n")

with open(f"{root}/THIRD_PARTY_NOTICES.md", "w") as handle:
    handle.write("\n".join(out))
print(f"THIRD_PARTY_NOTICES.md: {len(third_party)} crates, {len(texts)} distinct license texts, {len(missing)} without a file.")
